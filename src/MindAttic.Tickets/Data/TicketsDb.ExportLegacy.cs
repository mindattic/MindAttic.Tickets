using System.Globalization;
using System.Text;
using System.Text.Json;

namespace MindAttic.Tickets.Data;

/// <summary>One row read from one of the legacy planning tables (<see cref="TicketsDb.LegacyTables"/>), by column name.</summary>
public sealed record LegacyRow(string Table, IReadOnlyList<string> Columns, IReadOnlyList<object?> Values);

/// <summary>One legacy table's row count as written to the export, and as read from the live table right after: a
/// mismatch means a write landed on it mid-export (these tables are frozen, so that would itself be a bug).</summary>
public sealed record LegacyExportCount(string Table, int Exported, int Live);

public sealed partial class TicketsDb
{
    /// <summary>
    /// The tables that held a repo's planning before the ticket tree (frozen by M.TIX-T402; stories, epics and
    /// backlog writes now go through ticket levels instead): <c>epics</c>, <c>stories</c>, <c>backlog_items</c>,
    /// <c>backlog_refs</c> (a backlog item's links to the story IDs it names) and <c>blocks</c> (each repo's file
    /// as ordered raw/epic/story/backlog/tickets sections, used to rebuild it byte-for-byte). Kept in the database
    /// for history; exported here so they could eventually be dropped from it without losing anything.
    /// </summary>
    private static readonly (string Table, string Order)[] LegacyTables =
    [
        ("epics", "repo, key"),
        ("stories", "uid"),
        ("backlog_items", "uid"),
        ("backlog_refs", "item_uid, story_id"),
        ("blocks", "repo, ordinal"),
    ];

    /// <summary>
    /// Every row of the legacy planning tables, read table by table in <see cref="LegacyTables"/> order, with each
    /// table's live row count read right after it finishes so a caller can verify the export against the tables as
    /// they stood (<c>tickets db export-legacy</c>).
    /// </summary>
    public (IReadOnlyList<LegacyRow> Rows, IReadOnlyList<LegacyExportCount> Counts) ExportLegacy()
    {
        var rows = new List<LegacyRow>();
        var counts = new List<LegacyExportCount>();
        foreach (var (table, order) in LegacyTables)
        {
            var exported = 0;
            using (var cmd = Command($"SELECT * FROM {table} ORDER BY {order}", null, []))
            using (var r = cmd.ExecuteReader())
            {
                var cols = Enumerable.Range(0, r.FieldCount).Select(r.GetName).ToList();
                while (r.Read())
                {
                    rows.Add(new LegacyRow(table, cols, Enumerable.Range(0, r.FieldCount).Select(i => r.IsDBNull(i) ? null : r.GetValue(i)).ToList()));
                    exported++;
                }
            }
            var live = Convert.ToInt32(Scalar($"SELECT COUNT(*) FROM {table}"), CultureInfo.InvariantCulture);
            counts.Add(new LegacyExportCount(table, exported, live));
        }
        return (rows, counts);
    }

    /// <summary>The legacy planning rows as one readable SQL dump, in the same INSERT-per-row style as <see cref="Dump"/>.</summary>
    public static string LegacyDump(IReadOnlyList<LegacyRow> rows)
    {
        var sb = new StringBuilder("-- MindAttic.Tickets legacy planning export: stories, epics, backlog items, blocks and backlog " +
            "links (frozen by M.TIX-T402; generated by 'tickets db export-legacy'). The ticket database is the store.\n");
        string? last = null;
        foreach (var row in rows)
        {
            if (row.Table != last) { sb.Append("\n-- ").Append(row.Table).Append('\n'); last = row.Table; }
            sb.Append("INSERT INTO ").Append(row.Table).Append(" (").Append(string.Join(", ", row.Columns)).Append(") VALUES (");
            sb.Append(string.Join(", ", row.Values.Select(v => v switch
            {
                null => "NULL",
                long n => n.ToString(CultureInfo.InvariantCulture),
                double d => d.ToString(CultureInfo.InvariantCulture),
                _ => "'" + v.ToString()!.Replace("'", "''", StringComparison.Ordinal) + "'",
            })));
            sb.Append(");\n");
        }
        return sb.ToString();
    }

    /// <summary>The same rows as a JSON copy: one array per table, in <see cref="LegacyTables"/> order.</summary>
    public static string LegacyJson(IReadOnlyList<LegacyRow> rows)
    {
        var byTable = LegacyTables.ToDictionary(t => t.Table, _ => new List<Dictionary<string, object?>>());
        foreach (var row in rows)
            byTable[row.Table].Add(Enumerable.Range(0, row.Columns.Count).ToDictionary(i => row.Columns[i], i => row.Values[i]));
        return JsonSerializer.Serialize(byTable, new JsonSerializerOptions { WriteIndented = true });
    }
}
